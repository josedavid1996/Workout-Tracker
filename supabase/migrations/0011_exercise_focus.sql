-- Per-exercise "focus" tag: the specific muscle region an exercise emphasizes most
-- (e.g. lateral vs posterior deltoid, triceps long head). Lives in its own table so the
-- pre-existing `exercises` catalog stays untouched. Shared, read-only catalog data:
-- no user_id, readable by any authenticated user, no write policies.
-- Seed generated from a biomechanics-based classification of the full catalog
-- (name, target, secondary muscles and instruction steps); exercises with no clear
-- emphasis (cardio, plyometrics, full-body) have no row.

create table exercise_focus (
  exercise_id text primary key references exercises(id) on delete cascade,
  focus text not null check (focus in (
    'adductors',
    'anterior_deltoid',
    'biceps_long_head',
    'biceps_short_head',
    'brachialis',
    'deep_core',
    'forearm_extensors',
    'forearm_flexors',
    'gastrocnemius',
    'gluteus_maximus',
    'gluteus_medius',
    'hamstrings',
    'lateral_deltoid',
    'lats',
    'lower_abs',
    'lower_back',
    'lower_chest',
    'mid_back',
    'mid_chest',
    'neck',
    'obliques',
    'posterior_deltoid',
    'quads_rectus_femoris',
    'quads_vastus',
    'rotator_cuff',
    'soleus',
    'triceps_lateral_head',
    'triceps_long_head',
    'triceps_medial_head',
    'upper_abs',
    'upper_chest',
    'upper_traps'
  )),
  confidence text not null check (confidence in ('high', 'medium', 'low')),
  is_stretch boolean not null default false
);

create index exercise_focus_focus_idx on exercise_focus (focus);

alter table exercise_focus enable row level security;

create policy exercise_focus_read on exercise_focus
  for select to authenticated using (true);

